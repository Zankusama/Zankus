#!/usr/bin/env bash
# acceptance-check.sh — 验收三问自检（v5.9.0）
# 用法: acceptance-check.sh <任务书文件>
# 三问（来自教材「验收三问」：①数字有出处吗 ②你自己的判断是哪三句 ③风险分级对了吗）：
#   ① 出处锚定 —— 关键断言必须带来源（实测/日期/来源/URL/查到），无出处=编造嫌疑
#   ② 防凑数 —— 必须有防作弊点名（凑数/编造/只贴）或可复现声明，否则结论可能注水
#   ③ 风险定档 —— 验收强度须按风险分级（全检/抽检/免检/领导亲验/对外发布），缺=验收力度错配风险
# 退出码: 0 = 三问过（③ 缺只警告不硬卡）；1 = ①/② 不过
# G6 写书后自动调用（stage-gate.sh 6 的 6d 步）——与 goal-lint 并列，机器强制。

BOOK="${1:-}"
if [ -z "$BOOK" ] || [ ! -f "$BOOK" ]; then
  echo "用法: acceptance-check.sh <任务书文件>"
  exit 2
fi

FAIL=0
pass() { echo "✅ [验收三问] $1"; }
fail() { echo "❌ [验收三问] $1"; FAIL=$((FAIL+1)); }
warn() { echo "⚠️ [验收三问] $1"; }

echo "===== 验收三问自检 ====="

# 问① 数字有出处吗：来源标记（实测/日期/来源/URL/查到）≥3 处，或「现状与任务 0」段含来源词
SRC_CNT=$(grep -cE '实测|日期|来源|URL|查到|https' "$BOOK")
if [ "$SRC_CNT" -ge 3 ]; then
  pass "① 出处锚定：来源标记 × ${SRC_CNT}（≥3，关键断言有出处）"
elif grep -qE '【现状与任务 0】' "$BOOK" && awk '/【现状与任务 0】/,0' "$BOOK" | grep -qE '实测|日期|来源|查到'; then
  pass "① 出处锚定：现状段含来源标记（实测数字有出处）"
else
  fail "① 出处锚定：来源标记仅 ${SRC_CNT} 处（<3 且现状段无来源）——关键断言无出处=编造嫌疑"
fi

# 问② 结论带判断吗（防凑数）：防作弊点名或可复现声明存在
if grep -qE '凑数|编造|只贴|做完了|空转' "$BOOK"; then
  pass "② 防凑数：含防作弊点名（凑数/编造/只贴/做完了）——结论注水有规则拦截"
elif grep -qE '可复现|复现步骤|来源与日期' "$BOOK"; then
  pass "② 防凑数：含可复现声明（结论可抽验）"
else
  fail "② 防凑数：无防作弊点名（凑数/编造/只贴）且无可复现声明——结论可能注水"
fi

# 问③ 风险定档了吗：验收强度按风险分级（全检/抽检/免检/领导亲验/验收强度）——缺只警告不硬卡（防误伤短任务书）
if grep -qE '全检|抽检|免检|领导亲验|验收强度|按风险|风险分级' "$BOOK"; then
  pass "③ 风险定档：含验收分级表述（全检/抽检/免检/领导亲验）——验收强度跟风险挂钩"
else
  warn "③ 风险定档：未见验收分级表述（全检/抽检/免检/领导亲验/验收强度）——长任务书建议显式声明验收强度档位（人工确认，不硬卡）"
fi

echo "-----------------------------"
if [ "$FAIL" -eq 0 ]; then
  echo "✅✅ 验收三问自检通过"
  exit 0
else
  echo "❌ 验收三问有 ${FAIL} 问不过——修完再发出"
  exit 1
fi
